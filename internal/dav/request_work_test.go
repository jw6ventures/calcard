// A write validates an object through two readings, the parsed tree's and the
// ObjectTimes' the analysis and the recurrence check go through. Both draw on
// the one pool the write has: the tree's own lookups of a zone it cannot follow
// end the pool, and the pool a whole validation draws on is spent by the zone's
// walks, whichever reading makes them.
func TestWriteValidationDrawsItsReadingsOnOnePool(t *testing.T) {
	raw := denseObservanceObject("FREQ=DAILY", "FREQ=DAILY;COUNT=10")

	t.Run("the parsed tree", func(t *testing.T) {
		useTimezoneOnsets(t, maxHeldOnsets)
		root, err := parseICalendarTree(ical.UnfoldLines(raw), readSubmitted)
		if err != nil {
			t.Fatal(err)
		}
		pool := ical.NewRequestWork(nil, 100_000)
		root.drawOn(pool)
		validateCalendarObject(root)
		if !pool.Exhausted() {
			t.Error("the parsed tree followed a dense zone without drawing on the pool its object was given")
		}
	})
	t.Run("the whole validation", func(t *testing.T) {
		useTimezoneOnsets(t, maxHeldOnsets)
		short := ical.NewRequestWork(nil, 1_000_000)
		validateCalendarObjectReadAs(raw, nil, readSubmitted, short)
		if !short.Exhausted() {
			t.Error("a validation followed a zone that costs two million units on a pool of one million")
		}
		useTimezoneOnsets(t, maxHeldOnsets)
		ample := ical.NewRequestWork(nil, 12_000_000)
		if _, fault := validateCalendarObjectReadAs(raw, nil, readSubmitted, ample); fault != nil || ample.Exhausted() {
			t.Errorf("a validation on a pool of twelve million units was refused (%+v) or exhausted it (%v)", fault, ample.Exhausted())
		}
	})
}

// A query the database cancels for the deadline's sake comes back as
// PostgreSQL's query_canceled (57014) as readily as a context error, and is told
// apart by the context that ended: the report's deadline gives the answer for a
// request it will not compute in full, a client that left gives 499, and the
// same code from a statement_timeout with the request still live is the
// server's failure.
func TestInterruptedReportIsToldApartByItsContext(t *testing.T) {
	canceled := &pq.Error{Code: "57014"}
	for _, test := range []struct {
		name       string
		ctx        func() (context.Context, context.CancelFunc)
		reportName string
		err        error
		handled    bool
		status     int
	}{
		{"deadline with a canceled query", func() (context.Context, context.CancelFunc) {
			return context.WithDeadline(t.Context(), time.Now().Add(-time.Second))
		}, "calendar-query", canceled, true, http.StatusForbidden},
		{"deadline with a context error", func() (context.Context, context.CancelFunc) {
			return context.WithDeadline(t.Context(), time.Now().Add(-time.Second))
		}, "free-busy-query", context.DeadlineExceeded, true, http.StatusForbidden},
		{"deadline of a multiget", func() (context.Context, context.CancelFunc) {
			return context.WithDeadline(t.Context(), time.Now().Add(-time.Second))
		}, "calendar-multiget", canceled, true, http.StatusInsufficientStorage},
		{"deadline met as the scan limit free-busy reports", func() (context.Context, context.CancelFunc) {
			return context.WithDeadline(t.Context(), time.Now().Add(-time.Second))
		}, "free-busy-query", fmt.Errorf("range too large: %w", errNumberOfMatchesExceeded), true, http.StatusForbidden},
		{"deadline with an unrelated failure", func() (context.Context, context.CancelFunc) {
			return context.WithDeadline(t.Context(), time.Now().Add(-time.Second))
		}, "calendar-query", errors.New("connection reset"), false, 0},
		{"client left", func() (context.Context, context.CancelFunc) {
			ctx, cancel := context.WithCancel(t.Context())
			cancel()
			return ctx, cancel
		}, "calendar-query", canceled, true, statusClientClosedRequest},
		{"statement timeout on a live request", func() (context.Context, context.CancelFunc) {
			return context.WithCancel(t.Context())
		}, "calendar-query", canceled, false, 0},
	} {
		t.Run(test.name, func(t *testing.T) {
			ctx, cancel := test.ctx()
			defer cancel()
			req := httptest.NewRequest("REPORT", "/dav/calendars/1/", nil).WithContext(ctx)
			rr := httptest.NewRecorder()
			if handled := (&DavServer{}).answerInterruptedReport(rr, req, test.reportName, test.err); handled != test.handled || handled && rr.Code != test.status {
				t.Fatalf("handled %v with status %d, want %v with %d", handled, rr.Code, test.handled, test.status)
			}
		})
	}
}

