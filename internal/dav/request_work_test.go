// A REPORT over many resources whose zones each cost seconds to follow is
// bounded as a whole: the request's pool runs out after a few of them, and
// every resource after is kept without being judged, as one whose expansion ran
// out of work is, instead of costing its own seconds. Without the pool the
// thirty would take half a minute.
func TestCalendarQueryOverHostileZonesIsBoundedAsAWhole(t *testing.T) {
	useTimezoneOnsets(t, maxHeldOnsets)
	h := hostileRecurrenceServer()
	h.store.Events = &fakeEventRepo{ignoreFilter: true, events: hostileResources(30, "")}

	rr, elapsed := reportOver(t, h, queryHead+`<D:getetag/>`+queryTail)
	ms := decodeMultistatus(t, rr)
	if elapsed > 6*time.Second && !raceDetectorEnabled {
		t.Errorf("took %v, want the request's pool to end it within 6s", elapsed)
	}
	// None of the events is on the day asked about, so a resource is listed
	// only when its judgment was cut short: the ones before the pool ran out
	// are judged and left out, and every one from there on is kept.
	kept := len(ms.Responses)
	if kept == 0 || kept == 30 {
		t.Fatalf("%d of 30 resources listed, want the first few judged and left out and the rest kept", kept)
	}
	for i, response := range ms.Responses {
		if want := fmt.Sprintf("/dav/calendars/1/hostile-%02d.ics", 30-kept+i); len(response.Hrefs) != 1 || response.Hrefs[0] != want {
			t.Fatalf("response %d is %v, want %s: the resources kept are those after the pool ran out", i, response.Hrefs, want)
		}
	}
	t.Logf("%d of 30 resources kept after %v", kept, elapsed)
}

// The same REPORT over an ordinary calendar is untouched by the pool however
// many resources it holds: every resource is judged, and the answer is the exact
// one. A thousand resources each read their zone and expand a series, which
// would run a pool dry if each were charged a chunk of it rather than its work.
func TestCalendarQueryOverAnOrdinaryCalendarIsUnaffectedByThePool(t *testing.T) {
	useTimezoneOnsets(t, maxHeldOnsets)
	h := hostileRecurrenceServer()
	const n = 1000
	events := make(map[string]*store.Event, n)
	for i := range n {
		uid := fmt.Sprintf("ordinary-%02d", i)
		// Every third event is on the day asked about.
		day := 5
		if i%3 == 0 {
			day = 1
		}
		lines := []string{"BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Test//EN"}
		lines = append(lines, observanceZone(2, 0, "FREQ=YEARLY;BYMONTH=3;BYDAY=2SU")...)
		lines = append(lines, "BEGIN:VEVENT", "UID:"+uid, "DTSTAMP:20240101T000000Z",
			fmt.Sprintf("DTSTART;TZID=Many:2030010%dT093000", day), fmt.Sprintf("DTEND;TZID=Many:2030010%dT103000", day),
			"RRULE:FREQ=WEEKLY;COUNT=60", "END:VEVENT", "END:VCALENDAR", "")
		events["1:"+uid] = &store.Event{ID: int64(i + 1), CalendarID: 1, UID: uid, ResourceName: uid, ETag: "e", RawICAL: strings.Join(lines, "\r\n")}
	}
	h.store.Events = &fakeEventRepo{ignoreFilter: true, events: events}

	rr, elapsed := reportOver(t, h, queryHead+`<D:getetag/>`+queryTail)
	ms := decodeMultistatus(t, rr)
	if want := (n + 2) / 3; len(ms.Responses) != want {
		t.Errorf("%d of %d resources listed, want the %d on the day asked about", len(ms.Responses), n, want)
	}
	if elapsed > 6*time.Second && !raceDetectorEnabled {
		t.Errorf("took %v for an ordinary calendar", elapsed)
	}
}

