// One pool serves the filter's every element and the projection's reparse of the
// resource: judging a resource under a hundred time-range elements costs what
// following its zone once does, and the request's pool holds that and the
// projection of the same resource after it.
func TestPoolIsSharedByFilterElementsAndTheProjection(t *testing.T) {
	event := store.Event{UID: "shared", RawICAL: manyObservanceObject("shared", 40, 0, "FREQ=WEEKLY;COUNT=4")}
	elements := make([]compFilter, 100)
	for i := range elements {
		day := fmt.Sprintf("2030%02d01T000000Z", 1+i%12)
		elements[i] = compFilter{Name: "VEVENT", TimeRange: &timeRange{Start: day, End: strings.Replace(day, "01T", "02T", 1)}}
	}
	filter := &calFilter{CompFilter: compFilter{Name: "VCALENDAR", CompFilter: elements}}
	expand := newCalendarDataProjection(&calendarDataEl{Expand: &calendarRange{Start: time.Date(2024, 1, 1, 0, 0, 0, 0, time.UTC), End: time.Date(2024, 2, 1, 0, 0, 0, 0, time.UTC)}}, floatingZone{})

	useTimezoneOnsets(t, maxHeldOnsets)
	pool := ical.NewRequestWork(nil, reportWorkBudget)
	if _, err := applyCalendarFilter(t.Context(), []store.Event{event}, filter, floatingZone{}, pool); err != nil {
		t.Fatal(err)
	}
	if pool.Exhausted() {
		t.Fatal("100 filter elements cost the report's pool more than following the zone once")
	}
	if _, err := filterICalendarData(event.RawICAL, expand.withPool(pool)); err != nil {
		t.Fatalf("the projection of the resource was refused: %v", err)
	}
	if pool.Exhausted() {
		t.Error("the projection of the resource cost the report's pool more than it holds")
	}

	// A pool too small for the zone is spent by the filter, which keeps the
	// resource unsettled, and the projection of the same request is refused
	// for it.
	useTimezoneOnsets(t, maxHeldOnsets)
	small := ical.NewRequestWork(nil, 1_000_000)
	if kept, err := applyCalendarFilter(t.Context(), []store.Event{event}, filter, floatingZone{}, small); err != nil || len(kept) != 1 {
		t.Fatalf("a verdict reached on spent work was not kept unsettled: %d resources, %v", len(kept), err)
	}
	if _, err := filterICalendarData(event.RawICAL, expand.withPool(small)); err == nil {
		t.Error("the projection ran on a pool the filter had spent")
	}
}

// A collection MOVE or COPY validates every member before it writes any, and a
// retry of the transfer validates them again on a pool of its own. The members
// of one attempt share its pool, so the work of the attempt is bounded: a
// member the pool cannot pay for is refused with the 403 max-instances a member over its limit
// is, in a 207 naming it.
func TestCollectionMoveOfManyDenseMembersIsBounded(t *testing.T) {
	useTimezoneOnsets(t, maxHeldOnsets)
	slug := "source"
	source := store.Calendar{ID: 1, UserID: 1, Name: "Source", Slug: &slug, CTag: 3}
	calendars := &fakeCalendarRepo{
		accessible: []store.CalendarAccess{{Calendar: source, Editor: true}},
		calendars:  map[int64]*store.Calendar{1: &source},
	}
	const members = 40
	events := &fakeEventRepo{ignoreFilter: true, events: hostileResources(members, "")}
	backend := &retryingCollectionBackend{}
	h := NewDavServer(Options{Store: &store.Store{Calendars: calendars, Events: events, CalendarCollections: backend}})

	req := httptest.NewRequest("MOVE", "/dav/calendars/source/", nil)
	req.Header.Set("Destination", "/dav/calendars/moved")
	req = req.WithContext(auth.WithUser(req.Context(), &store.User{ID: 1}))
	rr := httptest.NewRecorder()
	started := time.Now()
	h.ServeHTTP(rr, req)
	elapsed := time.Since(started)

	ms := decodeMultistatus(t, rr)
	if len(backend.transfers) != 0 {
		t.Fatalf("the backend was reached by a transfer with members that could not be validated")
	}
	refused := 0
	for _, response := range ms.Responses {
		if strings.Contains(response.Status, "403") {
			refused++
		}
	}
	if refused == 0 || refused >= members || refused != len(ms.Responses) {
		t.Errorf("%d members refused of %d, %d responses; want some members validated and the rest refused", refused, members, len(ms.Responses))
	}
	if !strings.Contains(rr.Body.String(), "max-instances") {
		t.Errorf("members were not refused with max-instances: %s", rr.Body.String())
	}
	// The pool is ical.ObjectWorkBudget, about ten seconds of work at its
	// worst.
	if elapsed > 14*time.Second && !raceDetectorEnabled {
		t.Errorf("took %v, want the transfer's pool to end it within 14s", elapsed)
	}
	t.Logf("%d of %d members refused after %v", refused, members, elapsed)
}

// retryingCollectionBackend refuses a collection transfer once as changed, then
// accepts it, which makes the handler validate the members again.
type retryingCollectionBackend struct {
	transfers []store.CalendarCollectionTransfer
}

func (b *retryingCollectionBackend) TransferCalendarCollection(_ context.Context, transfer store.CalendarCollectionTransfer) (*store.CalendarCollectionTransferResult, error) {
	if len(b.transfers) == 0 {
		b.transfers = append(b.transfers, transfer)
		return nil, store.ErrResourceStateChanged
	}
	b.transfers = append(b.transfers, transfer)
	return &store.CalendarCollectionTransferResult{Calendar: &store.Calendar{ID: 9, UserID: 1, Name: "Moved"}, Created: true}, nil
}

