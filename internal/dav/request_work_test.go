// On any pool, validating an object either refuses it or reads the metadata a
// validation with work to spare reads: a reading that runs out of the pool
// partway through following the object's zone, which it would otherwise read
// as UTC, is a refusal, not an object stored at times its zone does not give.
// A one-observance zone keeps the sweep cheap; the pools that end the zone's
// walk after the parsed tree finished reading it lie a few thousand units
// apart, so the sweep steps through them finely.
func TestValidationOnAnyPoolRefusesOrReadsTheFundedMetadata(t *testing.T) {
	raw := manyObservanceObject("one", 1, 0, "")
	useTimezoneOnsets(t, maxHeldOnsets)
	funded, fault := validateCalendarObjectForStorage(raw, nil)
	if fault != nil {
		t.Fatalf("a funded validation refused the object: %+v", fault)
	}
	want := funded.Analysis.Metadata
	for _, reading := range []struct {
		name    string
		reading icalReading
	}{{"submitted", readSubmitted}, {"transferred", readTransferred}} {
		t.Run(reading.name, func(t *testing.T) {
			for units := 0; units <= 120_000; units += 500 {
				useTimezoneOnsets(t, maxHeldOnsets)
				got, fault := validateCalendarObjectReadAs(raw, nil, reading.reading, ical.NewRequestWork(nil, units))
				if fault != nil {
					continue
				}
				if !got.Analysis.Metadata.DTStart.Equal(*want.DTStart) || !got.Analysis.Metadata.DTEnd.Equal(*want.DTEnd) {
					t.Fatalf("on %d units the object is accepted with dtstart %v and dtend %v, want %v and %v or a refusal",
						units, got.Analysis.Metadata.DTStart.UTC(), got.Analysis.Metadata.DTEnd.UTC(), want.DTStart.UTC(), want.DTEnd.UTC())
				}
			}
		})
	}
}

