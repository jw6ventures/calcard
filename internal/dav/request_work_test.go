// An object whose answer does not depend on the pool is not refused for it. The
// readings of one write each stop at limits of their own, and the pool holds
// what both may spend: a series of ten weekly instances in a zone of 250
// observances, whose two readings spend their walk limits, is accepted at the
// times the zone gives, as is an event that does not recur in a zone of 350,
// whose dates the recurrence bounds leave unread.
func TestPutAcceptsAnObjectWhoseAnswerDoesNotDependOnThePool(t *testing.T) {
	for _, tt := range []struct {
		name        string
		observances int
		recurrence  string
	}{
		{"recurring", 250, "FREQ=WEEKLY;COUNT=10"},
		{"not recurring", 350, ""},
	} {
		t.Run(tt.name, func(t *testing.T) {
			useTimezoneOnsets(t, maxHeldOnsets)
			validated, fault := validateCalendarObjectForStorage(manyObservanceObject("independent", tt.observances, 0, tt.recurrence), nil)
			if fault != nil {
				t.Fatalf("refused: %+v", *fault)
			}
			metadata := validated.Analysis.Metadata
			wantStart, wantEnd := time.Date(2024, 1, 5, 6, 30, 0, 0, time.UTC), time.Date(2024, 1, 5, 7, 30, 0, 0, time.UTC)
			if metadata.DTStart == nil || !metadata.DTStart.Equal(wantStart) || metadata.DTEnd == nil || !metadata.DTEnd.Equal(wantEnd) {
				t.Errorf("dtstart %v and dtend %v, want %v and %v", metadata.DTStart, metadata.DTEnd, wantStart, wantEnd)
			}
		})
	}
}

// yearlyZoneObject holds a zone of count observances, each moving the clock
// forward by an hour from the second Sunday of March in a year, from a DTSTART
// of its own, and an event in June in it. Each rule is listed from 1601 through
// the present in about 1,400 units.
func yearlyZoneObject(count int) string {
	lines := []string{"BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Test//EN"}
	lines = append(lines, observanceZone(count, 0, "FREQ=YEARLY;BYMONTH=3;BYDAY=2SU")...)
	lines = append(lines, "BEGIN:VEVENT", "UID:yearly", "DTSTAMP:20240101T000000Z",
		"DTSTART;TZID=Many:20240605T093000", "DTEND;TZID=Many:20240605T103000", "END:VEVENT", "END:VCALENDAR", "")
	return strings.Join(lines, "\r\n")
}

func yearlyZoneReading(t *testing.T, raw string, pool *ical.RequestWork) time.Time {
	t.Helper()
	times := ical.NewObjectTimes(ical.UnfoldLines(raw), sharedTimezoneOnsets, pool)
	instant, ok := times.ResolvePropertyTime(`DTSTART;TZID=Many`, "20240605T093000")
	if !ok {
		t.Fatal("DTSTART does not resolve")
	}
	return instant
}

// Every listing a reading's lookups cause is charged to that reading and the
// request it answers. A reading that cannot afford the definition's listings
// cannot follow its zone; the listings it did complete are kept, those it did
// not are not held against their rules, and a later reading with work of its
// own finishes them and follows the zone.
func TestListingsAreChargedToTheReadingThatCausesThem(t *testing.T) {
	onsets := useTimezoneOnsets(t, maxHeldOnsets)
	raw := yearlyZoneObject(60)
	followed := time.Date(2024, 6, 5, 6, 30, 0, 0, time.UTC)

	// 60 listings cost about 85,000 units, the walks that would answer in their
	// place far more; the pool holds 50,000.
	short := ical.NewRequestWork(nil, 50_000)
	if got := yearlyZoneReading(t, raw, short); got.Equal(followed) {
		t.Fatal("a reading on a pool of 50,000 units followed a zone whose listings cost 85,000")
	}
	if !short.Exhausted() {
		t.Error("the pool that could not afford the listings does not report it")
	}
	listed := 0
	onsets.rules.Range(func(_ observanceRuleKey, rule *listedRule) bool {
		if rule.walked || rule.windowless {
			t.Errorf("a listing the reading could not afford was held against its rule: %+v", rule)
		}
		if rule.lister != nil && rule.listed() > 0 {
			listed++
		}
		return true
	})
	if listed == 0 || listed >= 60 {
		t.Errorf("%d of 60 rules are listed after the reading that could afford some of them, want some but not all", listed)
	}
	requireCacheWithinBudget(t, onsets)

	rich := ical.NewRequestWork(nil, ical.ObjectWorkBudget)
	if got := yearlyZoneReading(t, raw, rich); !got.Equal(followed) {
		t.Fatalf("a reading with work of its own resolved DTSTART to %v, want %v", got, followed)
	}
	if rich.Exhausted() {
		t.Error("a reading with work of its own was refused it")
	}

	// A listing already made costs the reading that asks for it nothing.
	empty := ical.NewRequestWork(nil, 0)
	if got := yearlyZoneReading(t, raw, empty); !got.Equal(followed) {
		t.Errorf("a reading on an empty pool resolved DTSTART to %v, want %v from the listings", got, followed)
	}
	if empty.Exhausted() {
		t.Error("answering from listings drew on the pool")
	}
}

// Many observances of distinct DTSTARTs in one definition are charged to the
// one reading: a reading that follows a definition of two hundred leaves the
// request's pool with what they cost, and no more than the reading may spend.
func TestManyObservancesAreChargedToOneReading(t *testing.T) {
	useTimezoneOnsets(t, maxHeldOnsets)
	raw := yearlyZoneObject(200)
	followed := time.Date(2024, 6, 5, 6, 30, 0, 0, time.UTC)
	// 200 listings cost about 285,000 units.
	enough := ical.NewRequestWork(nil, 400_000)
	if got := yearlyZoneReading(t, raw, enough); !got.Equal(followed) || enough.Exhausted() {
		t.Fatalf("a reading on a pool of 400,000 units resolved DTSTART to %v, exhausted %v; want %v from 200 listings", got, enough.Exhausted(), followed)
	}
	useTimezoneOnsets(t, maxHeldOnsets)
	short := ical.NewRequestWork(nil, 200_000)
	if got := yearlyZoneReading(t, raw, short); got.Equal(followed) || !short.Exhausted() {
		t.Errorf("a reading on a pool of 200,000 units resolved DTSTART to %v, exhausted %v; want the 200 listings refused for the pool", got, short.Exhausted())
	}
}

// hostileResources are n resources whose zones share no rule with each other,
// so every one's listings are paid for afresh: 40 observances each, about 8.6
// million units cold. Their events are on 5 January 2024, which the 2030
// calendar-query misses and the January 2024 queries reach.
func hostileResources(n int, rrule string) map[string]*store.Event {
	events := make(map[string]*store.Event, n)
	for i := range n {
		uid := fmt.Sprintf("hostile-%02d", i)
		events["1:"+uid] = &store.Event{
			ID: int64(i + 1), CalendarID: 1, UID: uid, ResourceName: uid, ETag: "e",
			RawICAL: manyObservanceObject(uid, 40, i*40, rrule),
		}
	}
	return events
}

