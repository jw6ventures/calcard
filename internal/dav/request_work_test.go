// A collection transfer whose pool runs out while a member's reading is
// following its zone refuses that member with max-instances rather than
// storing the times it would have read as UTC: every member the preflight
// passes on carries the metadata a validation with work to spare reads. Seven
// 40-observance members, one of 9 and then the one the pool runs out on, each
// accepted by PUT on its own, spend the attempt's pool to within the reading of
// the last member's zone.
func TestCollectionTransferRefusesAMemberWhoseZoneThePoolCouldNotFollow(t *testing.T) {
	if raceDetectorEnabled {
		t.Skip("spends a whole transfer's pool, which the race detector makes too slow")
	}
	useTimezoneOnsets(t, maxHeldOnsets)
	base := time.Date(2024, 1, 1, 0, 0, 0, 0, time.UTC)
	events := map[string]*store.Event{}
	add := func(position int, uid, raw string) {
		events["1:"+uid] = &store.Event{ID: int64(position), CalendarID: 1, UID: uid, ResourceName: uid, ETag: "e", RawICAL: raw,
			LastModified: base.Add(-time.Duration(position) * time.Minute)}
	}
	for i := range 7 {
		add(i+1, fmt.Sprintf("forty-%d", i), manyObservanceObject(fmt.Sprintf("forty-%d", i), 40, i*40, ""))
	}
	add(8, "nine", manyObservanceObject("nine", 9, 50_000, ""))
	add(9, "last", manyObservanceObject("last", 40, 100_000, ""))
	funded := map[string]store.EventWriteMetadata{}
	for _, event := range events {
		validated, fault := validateCalendarObjectForStorage(event.RawICAL, nil)
		if fault != nil {
			t.Fatalf("%s is refused on a write's own pool: %+v", event.UID, fault)
		}
		funded[event.UID] = validated.Analysis.Metadata
	}

	useTimezoneOnsets(t, maxHeldOnsets)
	h := NewDavServer(Options{Store: &store.Store{Events: lastModifiedFirstEvents{&fakeEventRepo{ignoreFilter: true, events: events}}}})
	req := httptest.NewRequest("MOVE", "/dav/calendars/1/", nil)
	req = ensureRequestCaches(req.WithContext(auth.WithUser(req.Context(), &store.User{ID: 1})))
	source := &store.CalendarAccess{Calendar: store.Calendar{ID: 1, UserID: 1, Name: "Source"}}
	members, failures, err := h.preflightCalendarCollectionMembers(req, &store.User{ID: 1}, source, "infinity", store.CalendarCollectionMove)
	if err != nil {
		t.Fatal(err)
	}
	for _, member := range members {
		want := funded[member.UID]
		if !member.Metadata.DTStart.Equal(*want.DTStart) || !member.Metadata.DTEnd.Equal(*want.DTEnd) {
			t.Errorf("%s is passed on with dtstart %v and dtend %v, want %v and %v or a refusal",
				member.UID, member.Metadata.DTStart.UTC(), member.Metadata.DTEnd.UTC(), want.DTStart.UTC(), want.DTEnd.UTC())
		}
	}
	for _, failure := range failures {
		if !slices.Equal(failure.fault.conditions, []string{"max-instances"}) {
			t.Errorf("%s is refused with %d %v, want max-instances", failure.href, failure.fault.status, failure.fault.conditions)
		}
	}
	if len(members)+len(failures) != len(events) {
		t.Errorf("%d members passed on and %d refused, want all %d accounted for", len(members), len(failures), len(events))
	}
}

// ordinaryMemberShapes are the costliest ordinary series a collection holds:
// two years of days or 900 weekday instances in America/New_York, 900 weekday
// instances and two years of days in an Outlook-style zone, an unbounded daily
// series, and 1,000 hours.
func ordinaryMemberShapes() []string {
	ny := func(rrule string) string {
		return buildCalendarObject(buildVEvent("m", "DTSTART;TZID=America/New_York:20240101T100000", "DTEND;TZID=America/New_York:20240101T110000", "RRULE:"+rrule))
	}
	outlook := func(rrule string) string {
		return buildCalendarObject(instancesOutlookEastern, buildVEvent("m", "DTSTART;TZID=Eastern Standard Time:20240101T100000", "DTEND;TZID=Eastern Standard Time:20240101T110000", "RRULE:"+rrule))
	}
	return []string{
		ny("FREQ=DAILY;UNTIL=20260101T000000Z"),
		ny("FREQ=WEEKLY;BYDAY=MO,TU,WE,TH,FR;COUNT=900"),
		outlook("FREQ=WEEKLY;BYDAY=MO,TU,WE,TH,FR;COUNT=900"),
		outlook("FREQ=DAILY;UNTIL=20260101T000000Z"),
		buildCalendarObject(buildVEvent("m", "DTSTART:20240101T100000Z", "DTEND:20240101T110000Z", "RRULE:FREQ=DAILY")),
		outlook("FREQ=HOURLY;COUNT=1000"),
	}
}

